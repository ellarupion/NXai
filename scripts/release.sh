#!/usr/bin/env bash
#
# Метка версии на текущем коммите.
#
# Зачем. Откатиться можно только к тому, что умеешь назвать. Без меток «версия» — это
# хэш коммита, и чтобы вернуться к состоянию, которое работало, приходится угадывать
# его в истории по датам. Метка даёт имя и короткое описание.
#
#   scripts/release.sh v1.4 "партия постов на день, учёт расходов на ИИ"
#
# После этого на сервере:
#
#   git fetch --tags && git checkout v1.4        # встать на версию
#   git checkout main && git pull                # вернуться к текущей
#
# Откат кода не откатывает базу. Если между версиями были миграции, схема останется
# новой — старый код может не запуститься. Порядок такой: сначала восстановить дамп
# (scripts/backup.sh --restore-check покажет, что дамп живой), потом вставать на метку.

set -euo pipefail
cd "$(dirname "$0")/.."

VERSION="${1:-}"
SUMMARY="${2:-}"

[ -n "$VERSION" ] || { echo "нужен номер версии, например: $0 v1.4 \"суть\"" >&2; exit 1; }
[ -n "$SUMMARY" ] || { echo "нужна короткая суть версии вторым аргументом" >&2; exit 1; }

case "$VERSION" in
    v*) ;;
    *)  echo "версия должна начинаться с v (v1.4)" >&2; exit 1 ;;
esac

# Метка на грязном дереве врёт: она укажет на коммит, а работал не он.
if [ -n "$(git status --porcelain)" ]; then
    echo "в рабочем дереве есть незакоммиченные изменения — сначала коммит" >&2
    exit 1
fi

if git rev-parse -q --verify "refs/tags/$VERSION" >/dev/null; then
    echo "метка $VERSION уже существует" >&2
    exit 1
fi

# Аннотированная (-a), а не лёгкая: у неё есть автор, дата и текст — то есть метка сама
# отвечает, когда и что выпущено.
git tag -a "$VERSION" -m "$SUMMARY"
git push origin "$VERSION"

echo
echo "Версия $VERSION выпущена: $SUMMARY"
echo "Встать на неё на сервере: git fetch --tags && git checkout $VERSION"
echo "Вернуться к текущей:      git checkout main && git pull"
