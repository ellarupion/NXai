"""Настройки поведения системы: пороги, времена, лимиты.

Зачем отдельный слой. Всё поведение NXai было зашито константами в коде: сколько
постов переписывать за тик, сколько держать про запас, какой скор считать достаточным,
насколько понижать доверие к источнику. Поменять любое из этих чисел значило собрать
образ и перезапустить сервис на проде — то есть настройки, до которой нельзя
дотянуться, а такая настройка настройкой не является.

Здесь они собраны в одну схему с ГРАНИЦАМИ. Границы не украшение: значение вне
диапазона должно отвергаться формой в панели, а не ронять планировщик в три часа ночи.

Правило, по которому решается, где чему место:
  * порог или время ПОВЕДЕНИЯ — сюда;
  * инфраструктура (адрес базы, ключи, домен) — в .env;
  * то, что настраивать нечего (интервал технического heartbeat), — остаётся
    константой в коде.

Хранится в PanelSettings.automation одним JSONB, а не колонками: набор полей будет
меняться с каждой задачей, которая трогает поведение, и заводить миграцию под каждое
число — работа без смысла. Отсутствующая или пустая строка означает «все значения по
умолчанию», поэтому система работает и до первого захода в настройки.
"""

from pydantic import BaseModel, Field, model_validator
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from core.models.panel_settings import PanelSettings


class AutomationSettings(BaseModel):
    """Все настраиваемые пороги и времена. Значения по умолчанию — те же числа, что
    стояли константами в коде, чтобы переход на настройки ничего не изменил в
    поведении."""

    model_config = {"extra": "ignore"}

    # --- Деньги на ИИ ---------------------------------------------------------
    # 0 отключает потолок. По умолчанию выключен намеренно: включать ограничение,
    # которое может остановить работу, — решение владельца, а не наше. Но теперь оно
    # хотя бы есть: до этого «ничто не мешало за день потратить месячный бюджет».
    daily_budget_usd: float = Field(0.0, ge=0, le=1000)
    # На каком проценте потолка предупреждать, пока ничего ещё не остановлено.
    budget_warn_percent: int = Field(80, ge=50, le=99)

    @model_validator(mode="after")
    def check_consistency(self) -> "AutomationSettings":
        """Проверки, которые нельзя выразить границей одного поля. Пока такая одна,
        но метод заведён сразу: пороги «нижний/верхний» приходят парами, и ловить их
        рассогласование надо здесь, а не в момент, когда планировщик встал."""
        return self


async def get_automation(session: AsyncSession) -> AutomationSettings:
    """Значения по умолчанию, дополненные тем, что переопределил оператор.
    Пустая или отсутствующая строка настроек = все значения по умолчанию."""
    stored = (await session.execute(select(PanelSettings.automation).limit(1))).scalar_one_or_none()
    return AutomationSettings(**(stored or {}))


async def set_automation(session: AsyncSession, partial: dict) -> AutomationSettings:
    """Накладывает частичное обновление поверх текущих значений и проверяет НАБОР
    целиком, а не только пришедшие поля: иначе можно записать пару значений, каждое из
    которых в границах, а вместе они бессмысленны."""
    row = (await session.execute(select(PanelSettings).limit(1))).scalar_one_or_none()
    if row is None:
        row = PanelSettings()
        session.add(row)
        await session.flush()

    current = AutomationSettings(**(row.automation or {}))
    merged = AutomationSettings(**{**current.model_dump(), **partial})
    row.automation = merged.model_dump(mode="json")
    await session.flush()
    return merged
