"""Настройки поведения системы: пороги, времена, лимиты.

Зачем отдельный слой. Всё поведение NXai было зашито константами в коде: какой скор
считать достаточным, сколько постов переписывать за тик, насколько понижать доверие к
источнику. Поменять любое из этих чисел значило собрать образ и перезапустить сервис на
проде — то есть настройка, до которой нельзя дотянуться, а такая настройка настройкой
не является.

И это не теория. Порог отбора вместе со штрафом доверия однажды замкнулись в петлю:
каждое автоотклонение понижало доверие источнику, пониженное доверие делало порог
недостижимым, канал замолчал на недели. Чтобы разомкнуть петлю, пришлось править код и
пересобирать образ — при том что нужно было поменять два числа.

Границы здесь не украшение: значение вне диапазона должно отвергаться формой в панели,
а не ронять планировщик в три часа ночи. Плюс проверка ПАРАМИ — верхняя граница доверия
обязана быть выше нижней, и поймать это надо при сохранении, а не когда источник
застрянет на полу.

Правило, по которому решается, где чему место:
  * порог или время ПОВЕДЕНИЯ — сюда;
  * инфраструктура (адрес базы, ключи, домен) — в .env;
  * то, что настраивать нечего или нельзя, — остаётся константой в коде. Сюда попали
    интервалы запуска заданий: их читает APScheduler при старте процесса, и настройка
    в панели врала бы — значение поменялось, а планировщик работает по-старому до
    перезапуска. Также жёсткие лимиты Telegram (4096 символов на сообщение) — они не
    наши, и менять их бессмысленно.

Хранится в PanelSettings.automation одним JSONB, а не колонками: набор полей будет
меняться с каждой задачей, которая трогает поведение, и заводить миграцию под каждое
число — работа без смысла. Отсутствующая или пустая строка означает «все значения по
умолчанию», поэтому система работает и до первого захода в настройки.
"""

from pydantic import BaseModel, Field, model_validator
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from core.models.panel_settings import PanelSettings


class AutomationSettings(BaseModel):
    """Все настраиваемые пороги и времена. Значения по умолчанию — те же числа, что
    стояли константами в коде, чтобы переход на настройки ничего не изменил в
    поведении."""

    model_config = {"extra": "ignore"}

    # --- Деньги на ИИ ---------------------------------------------------------
    # 0 отключает потолок. По умолчанию выключен намеренно: включать ограничение,
    # которое может остановить работу, — решение владельца, а не наше.
    daily_budget_usd: float = Field(0.0, ge=0, le=1000)
    # На каком проценте потолка предупреждать, пока ничего ещё не остановлено.
    budget_warn_percent: int = Field(80, ge=50, le=99)

    # --- Отбор постов ---------------------------------------------------------
    # Во сколько раз пост должен обгонять медиану своего канала, чтобы попасть в
    # работу. Самое влиятельное число в системе: подняли — тема замолчала, опустили —
    # в «Проверку» полезло всё подряд.
    selection_score_threshold: float = Field(1.5, ge=0.1, le=10)
    # Сколько постов канала нужно, чтобы медиане можно было верить. Пока их меньше,
    # скор считается по сырым пересылкам — у нового источника медианы просто нет.
    min_samples_for_median: int = Field(5, ge=2, le=50)
    # Во сколько раз пул отбора шире заказа. Из широкого пула раскладываем по
    # подтемам: «топ-N по виральности» на практике даёт N постов про один инфоповод.
    selection_pool_factor: int = Field(4, ge=1, le=10)

    # --- Доверие источникам ---------------------------------------------------
    # Границы, в которых гуляет вес источника. Нижняя не может быть слишком низкой:
    # при множителе 0.1 посту нужно было набрать пятнадцать медиан канала, то есть
    # источник не выбирался из ямы уже никогда.
    min_trust_score: float = Field(0.5, ge=0.1, le=1.0)
    max_trust_score: float = Field(2.0, ge=1.0, le=5.0)
    # Насколько двигать вес источника. Дубликат — мягкий сигнал (просто повторил
    # чужую новость), ручное отклонение — сильный, удачный рерайт — плюс.
    trust_duplicate_penalty: float = Field(0.02, ge=0, le=0.5)
    trust_rejected_penalty: float = Field(0.05, ge=0, le=0.5)
    trust_success_bonus: float = Field(0.02, ge=0, le=0.5)

    # --- Дубликаты ------------------------------------------------------------
    # Косинусная близость, выше которой посты считаются одним и тем же.
    dedup_similarity_threshold: float = Field(0.92, ge=0.5, le=1.0)

    # --- Рерайт и расход ------------------------------------------------------
    # Сколько постов уходит в модель за один тик планировщика — потолок скорости трат.
    rewrite_batch_limit: int = Field(5, ge=1, le=50)
    # На сколько дней вперёд держим запас готовых постов — потолок смысла: писать
    # больше, чем тема успеет опубликовать, значит платить за то, что протухнет.
    rewrite_stock_days: int = Field(2, ge=1, le=7)
    min_rewrite_stock: int = Field(5, ge=1, le=50)
    # Сколько постов максимум в одной партии «на сегодня». Ограничение про человека,
    # а не про деньги: партию разбирают руками.
    max_daily_batch: int = Field(20, ge=1, le=50)
    # Короче этого рерайтить нечего: модель начнёт импровизировать, а на пустом
    # промпте — отвечать репликой «дай текст», которая уходила редактору как пост.
    min_rewritable_length: int = Field(60, ge=10, le=500)

    # --- Подтемы --------------------------------------------------------------
    # Сколько последних публикаций смотрим, решая, не приелась ли подтема.
    rubric_recent_window: int = Field(4, ge=1, le=20)

    # --- Перекрытие чужой рекламы ---------------------------------------------
    # Через сколько минут после обнаружения чужой рекламы ставить свой пост поверх.
    ad_cover_delay_minutes: int = Field(60, ge=5, le=480)

    @model_validator(mode="after")
    def check_consistency(self) -> "AutomationSettings":
        """Проверки, которые нельзя выразить границей одного поля: каждое значение по
        отдельности в пределах, а вместе набор бессмысленный."""
        if self.min_trust_score >= self.max_trust_score:
            raise ValueError(
                "Нижняя граница доверия должна быть меньше верхней: иначе вес источника "
                "не сможет меняться вовсе"
            )
        # Источник на дне доверия обязан сохранять шанс пройти порог. Скор считается
        # как «медиан канала × доверие», поэтому на полу посту нужно набрать
        # threshold / min_trust медиан. Двадцать медиан не набирает никто, и такая пара
        # значений означала бы тихое отключение всех просевших источников — ровно то,
        # что уже случалось, только тогда систему в это загоняла петля, а теперь в неё
        # можно было бы въехать руками через настройки.
        medians_needed = self.selection_score_threshold / self.min_trust_score
        if medians_needed > 10:
            raise ValueError(
                f"При таком пороге отбора источнику на дне доверия нужно набрать "
                f"{medians_needed:.0f} медиан канала — недостижимо. Понизьте порог "
                f"отбора либо поднимите нижнюю границу доверия"
            )
        if self.min_rewrite_stock > self.max_daily_batch * self.rewrite_stock_days:
            raise ValueError(
                "Минимальный запас больше, чем тема способна опубликовать за отведённые "
                "дни — рерайт будет писать в стол"
            )
        return self


async def get_automation(session: AsyncSession) -> AutomationSettings:
    """Значения по умолчанию, дополненные тем, что переопределил оператор.
    Пустая или отсутствующая строка настроек = все значения по умолчанию."""
    stored = (await session.execute(select(PanelSettings.automation).limit(1))).scalar_one_or_none()
    return AutomationSettings(**(stored or {}))


async def set_automation(session: AsyncSession, partial: dict) -> AutomationSettings:
    """Накладывает частичное обновление поверх текущих значений и проверяет НАБОР
    целиком, а не только пришедшие поля: иначе можно записать пару значений, каждое из
    которых в границах, а вместе они бессмысленны."""
    row = (await session.execute(select(PanelSettings).limit(1))).scalar_one_or_none()
    if row is None:
        row = PanelSettings()
        session.add(row)
        await session.flush()

    current = AutomationSettings(**(row.automation or {}))
    merged = AutomationSettings(**{**current.model_dump(), **partial})
    row.automation = merged.model_dump(mode="json")
    await session.flush()
    return merged
