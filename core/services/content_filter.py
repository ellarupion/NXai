"""Отсев того, что не должно доходить до рерайта: чужая реклама и посты без
текста.

Обе проблемы вылезли на проде одновременно и выглядели как «бот сошёл с ума».

Пост без текста. Пайплайн намеренно принимает пост-картинку (аудит, п.5.1) —
у такого поста бывает подпись, и она ценна. Но если подписи нет, рерайтить
нечего, а LLM получает пустой user_prompt и отвечает РАЗГОВОРОМ: «слышь, ты
чего замолчал, кидай текст». Эта реплика уходила редактору как готовый пост
на одобрение. Модель тут ни при чём — ей просто нечего было переписывать.

Чужая реклама. Источники продают свои курсы, интенсивы и консультации.
Такой пост исправно набирает пересылки, проходит порог виральности и
переписывается — вместе с чужим @username, ценой и призывом «пиши в личку».
Публиковать это у себя бессмысленно и вредно: канал рекламирует конкурента.

Отсев идёт на приёме, до попадания в очередь: рерайт таких постов — это
потраченные деньги на LLM и мусор в «Проверке».
"""

import re

# Ниже этого рерайт бессмысленен: переписывать нечего, а LLM начнёт
# импровизировать. Порог низкий намеренно — короткие ёмкие посты в нише
# встречаются, и терять их из-за перестраховки хуже, чем изредка пропустить
# слабый.
MIN_REWRITABLE_LENGTH = 60

# Причины автоотсева. Префикс auto_ отделяет их от причин РУЧНОГО отклонения
# (core/services/review.py:REJECTION_REASONS): те — сигналы к доводке персоны
# («канцелярит», «вода»), и подмешивать к ним «это была реклама источника»
# нельзя, иначе сводка у бота начнёт советовать править стиль там, где стиль
# ни при чём.
AUTO_REASON_AD = "auto_ad"
AUTO_REASON_NO_TEXT = "auto_no_text"

# Маркеры, каждого из которых достаточно самого по себе.
STRONG_AD_PATTERNS = [
    # Обязательная в РФ маркировка рекламы — сомнений не остаётся.
    (r"\berid\b", "маркировка erid"),
    (r"#реклама\b", "хештег #реклама"),
    (r"\bреклама\s*:", "пометка «реклама:»"),
    (r"на\s+правах\s+рекламы", "«на правах рекламы»"),
    (r"рекламодател", "упоминание рекламодателя"),
]

# Слабые: поодиночке встречаются и в обычных постах, поэтому нужен минимум два.
WEAK_AD_PATTERNS = [
    (r"\bпиши(те)?\s+(мне\s+)?в\s+(личку|лс|директ)", "призыв писать в личку"),
    (r"\bзапис(ь|аться|ывайся)\b", "запись на что-то"),
    (r"\b(интенсив|вебинар|марафон|мастер-?класс|курс[еауы]?)\b", "продукт-обучение"),
    (r"\bмест\s+(осталось|нет|всего)|\bпоследнее\s+место|группа\s+почти\s+закрыт", "дефицит мест"),
    (r"\bпромокод\b|\bскидк[аиу]\b", "промокод/скидка"),
    (r"\b\d+\s*(₽|руб|рублей)\b|\bстоимость\b|\bоплат[аиу]\b", "цена"),
    (r"\b\d+\s*реакц", "гейт по реакциям"),
    (r"\bссылка\s+в\s+(шапке|описании|закрепе)", "ссылка в шапке"),
    (r"\bуспей\b|\bне\s+упусти\b|\bторопись\b", "срочность"),
    (r"t\.me/\+|joinchat", "инвайт в закрытый канал"),
]

_STRONG = [(re.compile(p, re.IGNORECASE), label) for p, label in STRONG_AD_PATTERNS]
_WEAK = [(re.compile(p, re.IGNORECASE), label) for p, label in WEAK_AD_PATTERNS]
# Чужие @упоминания — сильный сигнал в паре с любым другим: свой канал себя
# по нику обычно не зовёт, а вот «пиши @эксперту» — типичная продажа.
_MENTION = re.compile(r"@[A-Za-z][A-Za-z0-9_]{4,}")


def is_too_short_to_rewrite(text: str) -> bool:
    return len(text.strip()) < MIN_REWRITABLE_LENGTH


def ad_signals(text: str) -> list[str]:
    """Список сработавших маркеров — попадает в лог, чтобы ложные срабатывания
    можно было разобрать, а не гадать, почему пост исчез."""
    found: list[str] = []
    for pattern, label in _STRONG:
        if pattern.search(text):
            found.append(f"!{label}")
    for pattern, label in _WEAK:
        if pattern.search(text):
            found.append(label)
    if _MENTION.search(text):
        found.append("чужое @упоминание")
    return found


def looks_like_ad(text: str) -> bool:
    """Один сильный маркер либо два слабых. Порог в два выбран так, чтобы
    обычный пост, где один раз мелькнуло слово «курс», не улетал в отвал."""
    signals = ad_signals(text)
    if any(s.startswith("!") for s in signals):
        return True
    return len(signals) >= 2
