"""Markdown от LLM → HTML для Telegram.

Зачем не отправлять Markdown напрямую. Telegram умеет parse_mode=Markdown, и
публикация им и пользовалась, но у этого режима два дефекта, и оба стоили нам
постов.

Первый: он ломается от одиночного «*», «_», «[» или «`» — Telegram отвечает
400 «can't parse entities». А спецсимволы в живом тексте неизбежны: «звонил
в 8*», «файл my_report», смайл-скобка после ссылки. Фолбэк на plain спасал от
потери поста, но выдавал в канал текст с голыми звёздочками — то есть хуже,
чем если бы разметки не было вовсе.

Второй: разные диалекты. Промпт рерайта просит телеграмный Markdown
(«*жирный*»), а модели по привычке пишут стандартный («**жирный**»). В
legacy-режиме «**жирный**» рендерится мусором.

HTML снимает оба: мы экранируем ВЕСЬ текст, а теги расставляем сами — значит
несбалансированный маркер физически не может превратиться в незакрытую
сущность, он просто останется символом. И «*», и «**» приводим к одному тегу.

Один случай экранирование не покрывает, и он найден фаззингом, а не
рассуждением: маркеры могут ПЕРЕСЕКАТЬСЯ. «**жирный _и** курсив_» даёт
«<b>жирный <i>и</b> курсив</i>» — все теги закрыты, но вложенность нарушена,
и Telegram отвергает такое так же, как незакрытые. Правила ниже работают
независимо друг от друга и это не ловят, поэтому результат проверяется
целиком (_is_well_formed), а на перепутанном входе возвращается
экранированный текст без оформления.

Побочная выгода, ради которой всё и затевалось: карточка редактора в Telegram
теперь показывает пост ровно так, как он выйдет в канал. Раньше она слалась
без parse_mode, и редактор одобрял текст с видимыми подчёркиваниями, не
понимая, что в канале они станут курсивом.
"""

import html
import re

from core.logging import get_logger

logger = get_logger(__name__)

# Плейсхолдер для кусков, внутри которых разметку разбирать нельзя (код).
# \x00 в тексте от LLM не встречается, но на всякий случай вычищаем его на входе.
_SENTINEL = "\x00{}\x00"

_FENCED = re.compile(r"```(?:[a-zA-Z0-9_+-]*\n)?(.*?)```", re.DOTALL)
_INLINE_CODE = re.compile(r"`([^`\n]+)`")
_LINK = re.compile(r"\[([^\]\n]+)\]\(([^)\s]+)\)")

# Жирный: и «**x**» (стандартный Markdown, так пишут модели), и «*x*»
# (телеграмный, так просит промпт рерайта) — оба в <b>. Различать их незачем:
# в постах для канала нужен один акцент, а не два уровня.
_BOLD_DOUBLE = re.compile(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", re.DOTALL)
_BOLD_SINGLE = re.compile(r"(?<!\*)\*(?=\S)([^*\n]+?)(?<=\S)\*(?!\*)")
_STRIKE = re.compile(r"~~(?=\S)(.+?)(?<=\S)~~", re.DOTALL)

# Подчёркивание и курсив. Требование «не буква/цифра вокруг» — против
# snake_case и ников: в «my_report_final» и «@lis_martovskiy» подчёркивания
# разметкой не являются, а раньше именно они и рвали парсинг.
_WORD = r"[^\W_]"
_UNDERLINE = re.compile(rf"(?<!{_WORD})__(?=\S)(.+?)(?<=\S)__(?!{_WORD})", re.DOTALL)
_ITALIC = re.compile(rf"(?<!{_WORD})_(?=\S)([^_\n]+?)(?<=\S)_(?!{_WORD})")

# Заголовки Markdown Telegram не поддерживает (промпт рерайта просит их не
# использовать, но модели иногда всё равно ставят) — превращаем в жирную строку,
# иначе в канал уходит «### Вывод».
_HEADING = re.compile(r"^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$", re.MULTILINE)

# Ссылку пускаем только с внятной схемой: «javascript:» в href — открытая
# дверь, а Telegram отдаёт клик по ссылке пользователю без предупреждения.
_SAFE_URL = re.compile(r"^(https?://|tg://|mailto:)", re.IGNORECASE)


_TAG = re.compile(r"<(/?)([a-zA-Z]+)[^>]*>")


def _is_well_formed(rendered: str) -> bool:
    """Теги закрыты и не пересекаются.

    Проверка нужна, потому что правила выше независимы друг от друга, а
    маркеры в тексте могут перекрываться: «**жирный _и** курсив_» даёт
    «<b>жирный <i>и</b> курсив</i>». Каждый тег закрыт, но вложенность
    нарушена — Telegram на таком отвечает 400. Ловится это только осмотром
    результата целиком, отдельным регулярным выражением не лечится."""
    stack: list[str] = []
    for closing, name in _TAG.findall(rendered):
        if closing:
            if not stack or stack.pop() != name:
                return False
        else:
            stack.append(name)
    return not stack


def to_telegram_html(text: str) -> str:
    """Markdown → HTML, пригодный для parse_mode=HTML.

    Всё, что не распознано как разметка, экранируется и остаётся текстом.
    Если разметка исходника оказалась перепутанной настолько, что теги
    пересеклись, возвращается экранированный текст без оформления: потерять
    жирный лучше, чем потерять сообщение."""
    if not text:
        return ""

    original = text.replace("\x00", "")
    text = original
    stash: list[str] = []

    def keep(rendered: str) -> str:
        """Прячет готовый фрагмент от последующих правил."""
        stash.append(rendered)
        return _SENTINEL.format(len(stash) - 1)

    # 1. Блоки кода — первыми: внутри них «*» и «_» это текст, а не разметка.
    def repl_fenced(m):
        return keep(f"<pre>{html.escape(m.group(1).strip(), quote=False)}</pre>")

    text = _FENCED.sub(repl_fenced, text)

    def repl_inline_code(m):
        return keep(f"<code>{html.escape(m.group(1), quote=False)}</code>")

    text = _INLINE_CODE.sub(repl_inline_code, text)

    # 2. Ссылки — до экранирования, потому что дальше «(» и «)» никуда не
    #    денутся, а вот разбирать их вперемешку с остальным сложнее.
    def repl_link(m):
        label, url = m.group(1), m.group(2)
        if not _SAFE_URL.match(url):
            # Не ссылка, а что-то другое в квадратных скобках — возвращаем
            # как есть: экранирование всего текста идёт ниже, и escape здесь
            # дал бы «&amp;amp;».
            return m.group(0)
        return keep(f'<a href="{html.escape(url, quote=True)}">{html.escape(label, quote=False)}</a>')

    text = _LINK.sub(repl_link, text)

    # 3. Экранируем остаток. С этого момента «<» и «&» в тексте безопасны.
    text = html.escape(text, quote=False)

    # 4. Разметка. Двойные маркеры до одиночных, иначе «**x**» разберётся как
    #    пустой курсив вокруг «*x*».
    text = _HEADING.sub(r"<b>\1</b>", text)
    text = _BOLD_DOUBLE.sub(r"<b>\1</b>", text)
    text = _UNDERLINE.sub(r"<u>\1</u>", text)
    text = _STRIKE.sub(r"<s>\1</s>", text)
    text = _BOLD_SINGLE.sub(r"<b>\1</b>", text)
    text = _ITALIC.sub(r"<i>\1</i>", text)

    # 5. Возвращаем спрятанное — с конца: фрагмент мог поглотить плейсхолдер
    #    предыдущего (код-спан внутри блока кода), и при прямом порядке
    #    вложенный плейсхолдер вставлялся бы уже после своей очереди и утекал
    #    в сообщение сырым «\x000\x00».
    for i in range(len(stash) - 1, -1, -1):
        text = text.replace(_SENTINEL.format(i), stash[i])

    if not _is_well_formed(text):
        logger.warning("tg_format.crossed_markup_fallback_plain", length=len(original))
        return html.escape(original, quote=False)
    return text


def visible_length(rendered: str) -> int:
    """Длина так, как её считает Telegram: разметка идёт отдельными
    entity-объектами и в лимит сообщения/подписи не входит.

    Нужна там, где по лимиту принимается решение (влезет ли пост в подпись к
    фото). len() по готовому HTML завышал бы длину на теги и гнал в отдельное
    сообщение посты, которые прекрасно помещались."""
    return len(html.unescape(_TAG.sub("", rendered)))


def escape(text: str) -> str:
    """Для служебных строк вокруг поста (заголовок карточки, название
    источника, подпись канала): они идут в том же сообщении, а parse_mode
    действует на него целиком — неэкранированный «<» в названии канала
    сломал бы всё сообщение."""
    return html.escape(text or "", quote=False)
